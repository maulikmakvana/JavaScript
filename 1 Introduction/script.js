// Case Sensitive

// JavaScript is a case-sensitive language.

// Example:

let name = "Maulik";
let Name = "Makvana";

// name and Name are different variables.


// Dynamically Typed

// JavaScript is dynamically typed.
// A variable does not have a fixed data type.

let value = 10;

value = "Hello";

value = true;


// The same variable can store different types of values.


// Loosely Typed

// JavaScript allows different types of values
// and also performs type conversion when required.

let number = 10;
let text = "20";

console.log(number + text);

// Output:
// 1020


